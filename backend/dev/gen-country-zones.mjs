// Generates src/lib/countryZones.ts (country → IANA time zones) from the system tz database's zone.tab.
//   node dev/gen-country-zones.mjs [/usr/share/zoneinfo/zone.tab]
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2] ?? '/usr/share/zoneinfo/zone.tab';
const byCountry = new Map();
for (const line of readFileSync(src, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [cc, , zone] = line.split('\t');
  (byCountry.get(cc) ?? byCountry.set(cc, []).get(cc)).push(zone);
}
const packed = [...byCountry].sort(([a], [b]) => a.localeCompare(b)).map(([cc, zones]) => `${cc}:${zones.join(',')}`).join(';');
writeFileSync(
  new URL('../src/lib/countryZones.ts', import.meta.url),
  `// Generated by dev/gen-country-zones.mjs from the IANA tz database (zone.tab). Do not edit.
const PACKED = '${packed}';

/** ISO country code → its IANA time zones. */
export const COUNTRY_ZONES: Map<string, string[]> = new Map(PACKED.split(';').map((e) => {
  const [cc, zones] = e.split(':');
  return [cc, zones.split(',')];
}));
`,
);
console.log(`${byCountry.size} countries, ${[...byCountry.values()].flat().length} zones, ${packed.length} chars`);
