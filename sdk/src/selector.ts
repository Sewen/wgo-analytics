const esc = (s: string) => s.replace(/[^\w-]/g, '\\$&')
const quote = (v: string) => `"${v.replace(/["\\]/g, '\\$&')}"`

export function stableId(id: string): boolean {
  if (id.length > 40 || /[:\s]/.test(id)) return false // React useId etc.
  const digits = (id.match(/\d/g) || []).length
  if (digits / id.length > 0.3) return false
  if (/^[0-9a-f]{8,}$/i.test(id) || /[0-9a-f]{8}-[0-9a-f]{4}/i.test(id)) return false
  if (id.length >= 12 && !/[-_]/.test(id) && /\d/.test(id) && /[a-z]/i.test(id)) return false // random hash
  return true
}

// Utility-first CSS (Tailwind, UnoCSS, Bootstrap utilities…) describes layout, not meaning: `w-full`, `py-6`,
// `grid-cols-1`, `md:flex`, `bg-[#fff]`. Such classes make selectors long and break on every restyle.
const UTILITY =
  /^-?(?:(?:[mp][xytrblse]?|gap|space|inset|top|right|bottom|left|start|end|z|order|w|h|size|min|max|basis|grow|shrink|flex|grid|col|row|cols|rows|auto|text|font|leading|tracking|line|decoration|indent|align|whitespace|break|bg|from|via|to|fill|stroke|border|divide|outline|ring|shadow|opacity|rounded|accent|blur|backdrop|transition|duration|ease|delay|animate|transform|scale|rotate|translate|skew|origin|overflow|overscroll|object|aspect|columns|place|items|justify|self|content|float|clear|box|cursor|select|pointer|resize|scroll|snap|touch|sr|d|g|gx|gy|fs|fw|lh|position)-|(?:flex|grid|block|inline|table|contents|hidden|visible|invisible|collapse|static|fixed|absolute|relative|sticky|truncate|uppercase|lowercase|capitalize|italic|antialiased|container|group|peer|underline|grow|shrink|border|rounded|shadow|transition)$)/

export function stableClass(c: string): boolean {
  if (c.length > 30 || /^(css|sc|jsx|emotion|styled|svelte|astro)-/.test(c)) return false
  if (/[:[\]/!.%#()@]/.test(c)) return false // variants (md:flex), arbitrary values (w-[3px]), fractions (w-1/2)
  if (UTILITY.test(c)) return false
  // a token like "1x2y3z" mixes digits and letters; generated by CSS-in-JS
  return !c.split(/[-_]/).some((t) => t.length >= 4 && /\d/.test(t) && /[a-z]/i.test(t))
}

/** Attributes that identify an element on purpose: test ids, form field names, accessible labels. */
const HOOKS = ['data-testid', 'data-test', 'data-cy', 'data-qa', 'data-track', 'data-wgo', 'name', 'aria-label', 'role']

function segment(el: Element): string {
  let s = el.tagName.toLowerCase()
  for (const a of HOOKS) {
    const v = el.getAttribute(a)
    if (v && v.length <= 40 && !(a === 'role' && v === el.tagName.toLowerCase())) {
      s += `[${a}=${quote(v)}]`
      break
    }
  }
  if (s.indexOf('[') < 0) s += Array.from(el.classList).filter(stableClass).slice(0, 2).map((c) => '.' + esc(c)).join('')
  const p = el.parentElement
  if (!p) return s
  let ambiguous = false
  let idx = 0
  let n = 0
  for (const sib of Array.from(p.children)) {
    if (sib.tagName === el.tagName) { n++; if (sib === el) idx = n }
    if (sib !== el) {
      try { if (sib.matches(s)) ambiguous = true } catch { if (sib.tagName === el.tagName) ambiguous = true }
    }
  }
  return ambiguous && n > 1 ? `${s}:nth-of-type(${idx})` : s
}

function unique(sel: string, el: Element): boolean {
  try {
    const all = el.ownerDocument.querySelectorAll(sel)
    return all.length === 1 && all[0] === el
  } catch {
    return false
  }
}

/** The shortest path (max 5 levels) that uniquely identifies the element, anchored at a stable id if one is near. */
export function selector(el: Element): string {
  const parts: string[] = []
  let cur: Element | null = el
  while (cur && parts.length < 5) {
    if (cur.id && stableId(cur.id)) { parts.unshift('#' + esc(cur.id)); break }
    const tag = cur.tagName
    if ((tag === 'BODY' || tag === 'HTML') && cur !== el) break
    parts.unshift(segment(cur))
    if (unique(parts.join(' > '), el)) break
    cur = cur.parentElement
  }
  return parts.join(' > ')
}
